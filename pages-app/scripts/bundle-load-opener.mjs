import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(root, "public/load-opener.css"), "utf8");
const fflate = readFileSync(join(root, "node_modules/fflate/umd/index.js"), "utf8");
const runtime = readFileSync(join(root, "scripts/load-opener-standalone.js"), "utf8");
const script = `${fflate}\n${runtime}`;

const outDir = join(root, "src/generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "load-opener-embedded.ts"),
  `// Generated by scripts/bundle-load-opener.mjs — do not edit by hand.\nexport const LOAD_OPENER_CSS = ${JSON.stringify(css)};\nexport const LOAD_OPENER_SCRIPT = ${JSON.stringify(script)};\n`,
  "utf8",
);

console.log("Generated self-contained load opener bundle (" + Math.round(script.length / 1024) + " KB script).");
